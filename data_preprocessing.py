import pandas as pd
import numpy as np

"""# 1. LOADING AND COMBINING DATASETS"""

chicago_df = pd.read_csv('Chicago_listings (1).csv')
nola_df = pd.read_csv('New Orleans_listings.csv')

# Chicago Listings data first look
chicago_df.head()

chicago_df.shape

#New Orleans Listings data first look
nola_df.head()

nola_df.shape

# Adding a 'City' column to each dataframe before combining
chicago_df['city'] = 'Chicago'
nola_df['city'] = 'New Orleans'

# Combining both datasets vertically
df = pd.concat([chicago_df, nola_df], ignore_index=True)
df.head()

df.shape

"""# 2. DATA CLEANING & HANDLING MISSING VALUES"""

# Drop rows where critical operational or location data is missing
df = df.dropna(subset=['price', 'latitude', 'longitude', 'host_id'])

# The 'neighbourhood_group' is completely empty in this dataset, so we drop it
if 'neighbourhood_group' in df.columns and df['neighbourhood_group'].isnull().all():
    df = df.drop(columns=['neighbourhood_group'])

# Handle missing reviews data
# A missing 'reviews_per_month' implies 0 reviews have been left
df['reviews_per_month'] = df['reviews_per_month'].fillna(0)
df['last_review'] = df['last_review'].fillna('No Reviews')

# Handle missing text/categorical data
df['host_name'] = df['host_name'].fillna('Unknown Host')
df['license'] = df['license'].fillna('Unlicensed/Exempt')

# Remove duplicate listings if they were accidentally scraped twice
df = df.drop_duplicates(subset=['id'])

"""# 3. TEXT STANDARDIZATION (Group and Replace Logic)"""

df['neighbourhood'] = df['neighbourhood'].astype(str).str.title().str.strip()
df['room_type'] = df['room_type'].astype(str).str.title().str.strip()

"""# 4. DATA TRANSFORMATION"""

# A. Categorize Price (Pricing Analysis)
def categorize_price(price):
    if price < 75:
        return 'Budget (<$75)'
    elif price <= 200:
        return 'Standard ($75-$200)'
    elif price <= 500:
        return 'Premium ($201-$500)'
    else:
        return 'Luxury (>$500)'

df['price_tier'] = df['price'].apply(categorize_price)

# B. Host Type Classification (Host Analysis)
# Group by host_id to count how many listings a host operates total across the dataset
df['total_host_listings'] = df.groupby('host_id')['id'].transform('count')

# Classify host behavior
df['host_type'] = np.where(
    df['total_host_listings'] >= 3,
    'Commercial (3+ Listings)',
    'Casual (1-2 Listings)'
)

# C. Booking Availability Status (Property Analysis)
def availability_status(days):
    if days == 0:
        return 'Fully Booked / Inactive'
    elif days < 90:
        return 'Low Availability (< 90 days)'
    elif days < 270:
        return 'Medium Availability'
    else:
        return 'High Availability (> 270 days)'

df['availability_tier'] = df['availability_365'].apply(availability_status)

# D. Engagement Level (Proxy for Popularity)
def engagement_level(reviews):
    if reviews == 0:
        return 'No Reviews'
    elif reviews <= 10:
        return 'Low Engagement'
    elif reviews <= 50:
        return 'Moderate Engagement'
    else:
        return 'High Engagement'

df['engagement_tier'] = df['number_of_reviews'].apply(engagement_level)

